def glyph_name(ch: str) -> str:
    return f"uni{ord(ch):04X}"


def draw(rows: list[str]):
    """One square contour per ink pixel; row 6 sits on the baseline."""
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        y0 = (CAP - 1 - r) * PX
        for c, cell in enumerate(row):
            if cell != "#":
                continue
            x0 = c * PX
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y0 + PX))
            pen.lineTo((x0 + PX, y0 + PX))
            pen.lineTo((x0 + PX, y0))
            pen.closePath()
    return pen.glyph()


def main() -> None:
    for ch, rows in G.items():
        assert len(rows) in (7, 8, 9), ch
        assert all(len(r) == 5 for r in rows), ch
    order = [".notdef", "space"] + [glyph_name(ch) for ch in G]
    fb = FontBuilder(EM, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {32: "space"} | {ord(ch): glyph_name(ch) for ch in G}
    fb.setupCharacterMap(cmap)
    glyphs = {".notdef": draw(["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"])}
    glyphs["space"] = TTGlyphPen(None).glyph()
    for ch, rows in G.items():
        glyphs[glyph_name(ch)] = draw(rows)
    fb.setupGlyf(glyphs)
    metrics = {name: (ADVANCE, 0) for name in order}
    metrics["space"] = (4 * PX, 0)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=CAP * PX, descent=-DESC * PX)
    fb.setupNameTable({"familyName": "2-Top Pixel", "styleName": "Regular"})
    fb.setupOS2(
        sTypoAscender=CAP * PX,
        sTypoDescender=-DESC * PX,
        sTypoLineGap=PX,
        usWinAscent=CAP * PX,
        usWinDescent=DESC * PX,
        sxHeight=5 * PX,
        sCapHeight=CAP * PX,
    )
    fb.setupPost()
    out = Path(__file__).resolve().parent.parent / "assets" / "fonts" / "twotop_pixel.ttf"
    out.parent.mkdir(parents=True, exist_ok=True)
    fb.save(str(out))
    print(f"wrote {out} ({len(G)} glyphs)")


if __name__ == "__main__":
    main()
